"""Labeled sample workspace for UI review. Never enabled in production."""

from __future__ import annotations

from datetime import timedelta
from pathlib import Path

from sqlalchemy import select
from sqlalchemy.orm import Session

from codecare.models import (
    DetectedIssue,
    FixProposal,
    GithubInstallation,
    Notification,
    Organization,
    OrganizationMember,
    Profile,
    PullRequestRecord,
    Repository,
    RepositoryScan,
    Subscription,
    VerificationRun,
    new_id,
    utcnow,
)
from codecare.security import hash_password
from codecare.services.orgs import bootstrap_org

DEMO_EMAIL = "demo@codecare.si"
DEMO_PASSWORD = "demo-review-pass"
SAMPLE = "[Sample]"
FIXTURE = Path(__file__).resolve().parents[3] / "samples" / "maintenance-fixture"
SAMPLE_APP = "def add(left: int, right: int) -> int:\n    return left + right\n"


def is_sample_repo(repo) -> bool:
    repo_id = str(getattr(repo, "github_repo_id", "") or "")
    full_name = str(getattr(repo, "full_name", "") or "")
    return repo_id.startswith("sample-") or full_name == "sample/maintenance-fixture"


def seed_demo(db: Session) -> str:
    profile = db.scalar(select(Profile).where(Profile.email == DEMO_EMAIL))
    if profile is None:
        profile = Profile(
            id=new_id(),
            email=DEMO_EMAIL,
            full_name="Demo Reviewer",
            password_hash=hash_password(DEMO_PASSWORD),
            email_verified_at=utcnow(),
        )
        db.add(profile)
        org = bootstrap_org(db, profile)
        org.name = "Sample workspace"
    else:
        member = db.scalar(select(OrganizationMember).where(OrganizationMember.profile_id == profile.id))
        org = db.get(Organization, member.organization_id) if member else bootstrap_org(db, profile)
    if org is None:
        raise RuntimeError("Demo workspace could not be created")
    existing = db.scalar(
        select(Repository).where(Repository.organization_id == org.id, Repository.github_repo_id == "sample-demo")
    )
    if existing:
        db.commit()
        return org.id

    installation = GithubInstallation(
        id=new_id(),
        organization_id=org.id,
        installation_id="sample-demo",
        account_login="sample",
        account_type="Organization",
        token_status="sample",
    )
    db.add(installation)
    db.flush()
    repo = Repository(
        id=new_id(),
        organization_id=org.id,
        installation_id=installation.id,
        github_repo_id="sample-demo",
        full_name="sample/maintenance-fixture",
        default_branch="main",
        private=False,
        language="Python",
        connected=True,
        health_status="attention",
        last_scanned_at=utcnow(),
    )
    db.add(repo)
    db.flush()
    scan = RepositoryScan(
        id=new_id(),
        organization_id=org.id,
        repository_id=repo.id,
        status="completed",
        trigger="sample",
        summary=f"{SAMPLE} Fixture scan completed. This is not a live GitHub result.",
        languages='["Python","JavaScript"]',
        commit_sha="sample000",
        completed_at=utcnow(),
    )
    db.add(scan)
    db.flush()
    issue = DetectedIssue(
        id=new_id(),
        organization_id=org.id,
        repository_id=repo.id,
        scan_id=scan.id,
        fingerprint="sample-vuln",
        title=f"{SAMPLE} Outdated dependency with a known advisory",
        category="vulnerability",
        severity="high",
        status="pr_opened",
        file_path="requirements.txt",
        evidence=f"{SAMPLE} requirements.txt pins an outdated package. Not fetched from GitHub.",
        diagnosis=f"{SAMPLE} Heuristic note only. No model was called.",
    )
    db.add(issue)
    db.flush()
    proposal = FixProposal(
        id=new_id(),
        organization_id=org.id,
        repository_id=repo.id,
        issue_id=issue.id,
        summary=f"{SAMPLE} Bump the pinned package. This patch was not generated by an AI provider.",
        patch='{"files":[{"path":"requirements.txt","note":"sample pin"}]}',
        provider="sample",
        status="verified",
    )
    db.add(proposal)
    db.flush()
    verification = VerificationRun(
        id=new_id(),
        organization_id=org.id,
        repository_id=repo.id,
        proposal_id=proposal.id,
        status="verified",
        log=f"{SAMPLE} Recorded as verified for UI review. Docker was not invoked.",
        tests_passed=3,
        tests_failed=0,
        completed_at=utcnow(),
    )
    db.add(verification)
    db.flush()
    db.add(
        PullRequestRecord(
            id=new_id(),
            organization_id=org.id,
            repository_id=repo.id,
            proposal_id=proposal.id,
            verification_id=verification.id,
            number=1,
            url="https://github.com/sample/maintenance-fixture/pull/1",
            title=f"{SAMPLE} Pin the vulnerable dependency",
            status="open",
            created_at=utcnow() - timedelta(hours=2),
        )
    )
    sub = db.scalar(select(Subscription).where(Subscription.organization_id == org.id))
    if sub:
        sub.plan = "none"
        sub.status = "inactive"
    db.add(
        Notification(
            id=new_id(),
            organization_id=org.id,
            profile_id=profile.id,
            title=f"{SAMPLE} Scan finished",
            body="Sample maintenance activity for review. No repository was contacted.",
        )
    )
    db.commit()
    return org.id
